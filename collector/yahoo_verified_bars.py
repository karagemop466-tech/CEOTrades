def to_bars(rows: list[tuple[int, float, float]]) -> list[dict]:
    by = {}
    for t, o, c in rows:
        d = datetime.fromtimestamp(int(t) + OFFSET, tz=timezone.utc).strftime("%Y-%m-%d")
        by[d] = {"d": d, "o": round(float(o), 4), "c": round(float(c), 4)}
    return [by[k] for k in sorted(by)]


def main() -> int:
    os.makedirs(bd.PRICE_CACHE, exist_ok=True)
    for tk, rows in BARS.items():
        bars = to_bars(rows)
        bd.save_bars(tk, bars, "yahoo:query1")
        print(f"{tk}: {len(bars)} bars {bars[0]['d']} .. {bars[-1]['d']}")
    return 0


